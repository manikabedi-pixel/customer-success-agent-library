from pathlib import Path


def _safe_text(value) -> str:
    """
    Convert a value to text without treating it as
    trusted Markdown formatting.
    """

    if value is None:
        return "Not provided"

    return (
        str(value)
        .replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("\r", " ")
        .replace("\n", " ")
        .replace("`", "\\`")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )


def render_migration_markdown(report: dict) -> str:
    """
    Render a human-readable migration assessment.

    Does not change migration authorization.
    """

    lines = [
        "# Customer Data Migration Assessment",
        "",
        f"**Customer:** {_safe_text(report.get('customer_name'))}",
        f"**Deal ID:** {_safe_text(report.get('deal_id'))}",
        f"**Readiness:** {_safe_text(report.get('readiness_status'))}",
        "**Requires Human Review:** True",
        "**Migration Authorized:** False",
        "",
        "## Migration Requirements",
        "",
    ]

    requirements = report.get("requirements", [])

    if not requirements:
        lines.append(
            "No migration requirements identified by the current extractor."
        )

    for requirement in requirements:
        lines.append(
            f"- **{_safe_text(requirement.get('requirement_id'))}:** "
            f"{_safe_text(requirement.get('description'))}"
        )

    lines.extend([
        "",
        "## Source Systems",
        "",
    ])

    systems = report.get("source_systems", [])

    if not systems:
        lines.append("No source systems identified.")

    for system in systems:
        lines.append(
            f"- **{_safe_text(system.get('system_id'))}:** "
            f"{_safe_text(system.get('name'))} "
            f"(Owner: {_safe_text(system.get('owner'))})"
        )

    lines.extend([
        "",
        "## Datasets",
        "",
    ])

    datasets = report.get("datasets", [])

    if not datasets:
        lines.append("No datasets identified.")

    for dataset in datasets:
        lines.append(
            f"- **{_safe_text(dataset.get('dataset_id'))}:** "
            f"{_safe_text(dataset.get('name'))} "
            f"(Source: {_safe_text(dataset.get('source_system_id'))})"
        )

    lines.extend([
        "",
        "## Field Mappings",
        "",
    ])

    mappings = report.get("field_mappings", [])

    if not mappings:
        lines.append("No field mappings supplied.")

    for mapping in mappings:
        lines.append(
            f"- **{_safe_text(mapping.get('mapping_id'))}:** "
            f"{_safe_text(mapping.get('source_field'))} "
            f"→ {_safe_text(mapping.get('destination_field'))} "
            f"(Verified: {_safe_text(mapping.get('verified'))})"
        )

    lines.extend([
        "",
        "## Migration Risks",
        "",
    ])

    risks = report.get("risks", [])

    if not risks:
        lines.append("No risks generated by the current assessment rules.")

    for risk in risks:
        lines.append(
            f"- **{_safe_text(risk.get('risk_id'))}:** "
            f"{_safe_text(risk.get('description'))} "
            f"(Severity: {_safe_text(risk.get('severity'))})"
        )

    lines.extend([
        "",
        "## Readiness Findings",
        "",
    ])

    summary = report.get("readiness_summary", {})

    lines.append(
        f"**Raw Findings:** "
        f"{_safe_text(summary.get('total_raw_findings', 0))}"
    )

    lines.append(
        f"**Unique Findings:** "
        f"{_safe_text(summary.get('total_unique_findings', 0))}"
    )

    for finding in summary.get("unique_findings", []):
        lines.append(f"- {_safe_text(finding)}")

    lines.extend([
        "",
        "## Recommended Next Steps",
        "",
    ])

    recommendations = report.get("recommendations", [])

    if not recommendations:
        lines.append("No recommendations generated.")

    for recommendation in recommendations:
        lines.append(
            f"- **{_safe_text(recommendation.get('recommendation_id'))}:** "
            f"{_safe_text(recommendation.get('description'))}"
        )

    lines.extend([
        "",
        "## Human Approval",
        "",
    ])

    approval = report.get("approval", {})

    lines.append(
        f"**Decision:** "
        f"{_safe_text(approval.get('decision', 'pending'))}"
    )

    lines.append(
        f"**Verified:** "
        f"{_safe_text(approval.get('verified', False))}"
    )

    lines.extend([
        "",
        "---",
        "",
        "**Assessment Notice:** This report is advisory. "
        "It does not authorize migration execution.",
        "",
    ])

    return "\n".join(lines)


def save_migration_markdown(
    markdown: str,
    output_path: str | Path,
) -> Path:
    """
    Save the Markdown report to disk.
    """

    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)

    path.write_text(
        markdown,
        encoding="utf-8",
    )

    return path